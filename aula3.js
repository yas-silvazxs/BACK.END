//BOOLEANDO: "true" e "false"
/*
== -> igualdade
!= -> desigualdade
> -> maior que
< -> menor que
>= -> maior ou igual que
<= -> menor ou igual que
*/
console.log(10 == "10")
console.log(true == 1)
console.log(false == 0)

//igualdade escrita

console.log(10 === 1)
console.log(true === 1)
console.log(false === 0)